export type CitizenTranslationDict = typeof citizenTranslations.en;

function readStoredLang(): CitizenLang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'si' || saved === 'ta') return saved;
  } catch {
    // Ignore storage errors
  }
  return 'en';
}

export function useCitizenLanguage() {
  const [lang, setLangState] = useState<CitizenLang>(readStoredLang);

  useEffect(() => {
    const syncLang = () => setLangState(readStoredLang());
    window.addEventListener(LANG_EVENT, syncLang);
    window.addEventListener('storage', syncLang);
    return () => {
      window.removeEventListener(LANG_EVENT, syncLang);
      window.removeEventListener('storage', syncLang);
    };
  }, []);

  const setLang = useCallback((next: CitizenLang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Ignore storage errors
    }
    window.dispatchEvent(new Event(LANG_EVENT));
  }, []);

  const fontClass =
    lang === 'si'
      ? "font-['Noto_Sans_Sinhala',sans-serif]"
      : lang === 'ta'
      ? "font-['Noto_Sans_Tamil',sans-serif]"
      : '';

  return {
    lang,
    setLang,
    t: citizenTranslations[lang],
    fontClass,
  };
}